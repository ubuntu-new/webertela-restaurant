/**
 * The admin dictionary, and nothing that touches a database.
 *
 * This half is deliberately free of `server-only` so that client components —
 * the search box, the archive dialog, the image field — can translate too.
 * Anything that has to ask Postgres which language is set lives next door in
 * admin-i18n.ts, which is server-only and re-exports what is here.
 *
 * Splitting it this way is what let the last five Georgian screens move into
 * the dictionary instead of staying hardcoded.
 */

